func CloudflareIP(raw string) bool {
	ip, err := netip.ParseAddr(raw)
	if err != nil {
		return false
	}
	ip = ip.Unmap()
	for _, network := range cloudflareNetworks {
		if network.Contains(ip) {
			return true
		}
	}
	return false
}
